"""Eval runner: `python -m evals.run`.

Builds a deterministic reference research note for each golden-set question
(using the same tools the skill workflow uses — compute_metrics,
search_filings, compare_peers), grades each note with evals/graders.py, runs
the retrieval eval, prints a scorecard, and writes evals/results/<date>.json.

This runner does NOT call an LLM. Its purpose is to prove the eval mechanism
works end-to-end against a known-good note builder, giving a baseline score
to compare against when the metrics engine, retrieval, or skill instructions
change. Grading an actual Claude Code transcript is a natural next step, not
required for the MVP's eval-mindset demonstration.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

import yaml

from evals.graders import grade_response
from evals.retrieval_eval import run_retrieval_eval
from src.tools.filings_search import search_filings
from src.tools.fundamentals import get_fundamentals
from src.tools.metrics_engine import compute_ratios

GOLDEN_SET_PATH = Path(__file__).parent / "golden_set.yaml"
RESULTS_DIR = Path(__file__).parent / "results"

# Minimum acceptable mean score per grader before the runner exits nonzero.
THRESHOLDS = {
    "traceability": 0.95,
    "citation_coverage": 0.8,
    "safety": 1.0,
    "structure": 1.0,
    "coverage": 0.5,
}


def load_golden_set() -> list[dict[str, Any]]:
    with open(GOLDEN_SET_PATH, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def build_reference_note(item: dict[str, Any]) -> dict[str, Any]:
    """Assemble a note the way the skill workflow would, using real tool calls."""
    metrics_used: dict[str, Any] = {}
    citations: list[dict[str, str]] = []
    metrics_lines = []
    obs_lines = []

    for ticker in item["expected_tickers"]:
        fundamentals = get_fundamentals(ticker)
        if fundamentals is None:
            metrics_lines.append(f"- {ticker}: not in local filing corpus")
            continue
        computed = compute_ratios(fundamentals)
        metrics_used[ticker] = computed
        ratios = computed["ratios"]
        metrics_lines.append(
            f"- {ticker}: gross_margin={ratios['gross_margin']:.1%}, "
            f"net_debt_to_ebitda={ratios['net_debt_to_ebitda']:.1f}x, "
            f"pe_ratio={ratios['pe_ratio']:.1f}"
        )

        hits = search_filings(item["query_for_retrieval"], ticker=ticker, top_k=1)
        for hit in hits:
            citations.append({"ticker": hit["ticker"], "section": hit["section"]})
            obs_lines.append(
                f"- {ticker} shows relevant filing evidence "
                f"({hit['ticker']} {hit['form']} FY{hit['fiscal_year']}, \"{hit['section']}\")"
            )

    text = f"""# Research Note: {item['question']}

## Snapshot
Reviewed tickers: {', '.join(item['expected_tickers'])}.

## Metrics table
{chr(10).join(metrics_lines) if metrics_lines else '- no metrics computed'}

## Filing-backed observations
{chr(10).join(obs_lines) if obs_lines else '- no filing evidence retrieved'}

## Risks
- This is a reference note generated by the eval runner, not a full skill run.

## Open questions
- Tickers outside the local filing corpus need fundamentals added before they can be analyzed.

## What would change my mind
- Additional filings or updated fundamentals for the tickers above.

## View
- Neutral on the tickers above: this reference note is a mechanical stand-in to exercise the eval harness, not a real assessment, so no confident rating is stated.
"""
    return {"text": text, "metrics_used": metrics_used, "citations": citations}


def main() -> int:
    golden_set = load_golden_set()

    per_question_scores = []
    for item in golden_set:
        response = build_reference_note(item)
        scores = grade_response(response, item["expected_tickers"], item["expected_metrics"])
        per_question_scores.append({"id": item["id"], "scores": scores})

    retrieval_scores = run_retrieval_eval(golden_set)

    mean_scores: dict[str, float] = {}
    for grader_name in THRESHOLDS:
        values = [q["scores"][grader_name]["score"] for q in per_question_scores]
        mean_scores[grader_name] = round(sum(values) / len(values), 3) if values else 0.0

    print("=" * 60)
    print("EVAL SCORECARD")
    print("=" * 60)
    for grader_name, mean in mean_scores.items():
        threshold = THRESHOLDS[grader_name]
        status = "PASS" if mean >= threshold else "FAIL"
        print(f"{grader_name:20s} mean={mean:.3f}  threshold={threshold:.2f}  [{status}]")
    print("-" * 60)
    if retrieval_scores["mean_recall_at_k"] is not None:
        print(f"{'retrieval recall@5':20s} mean={retrieval_scores['mean_recall_at_k']:.3f}")
        print(f"{'retrieval MRR':20s} mean={retrieval_scores['mean_mrr']:.3f}")
    print("=" * 60)

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    result_path = RESULTS_DIR / "latest.json"
    with open(result_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                "mean_scores": mean_scores,
                "per_question": per_question_scores,
                "retrieval": retrieval_scores,
            },
            f,
            indent=2,
        )
    print(f"Results written to {result_path}")

    failed = [name for name, mean in mean_scores.items() if mean < THRESHOLDS[name]]
    if failed:
        print(f"REGRESSION: below threshold on: {', '.join(failed)}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
